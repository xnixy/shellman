//! An app of the list as a dock pin: the id the dock will find its windows by, and the program
//! to start it with and take its icon from.
//!
//! The dock groups windows by their AppUserModelID when they declare one, else by their
//! program's path (`winlist::identity`), so the pin is: a Store app's id; an id a shortcut names
//! (Firefox's, VS Code's), which such apps give their windows too; and otherwise the program's
//! path, lowercased. A shortcut is pinned as the program it starts, as when one is dropped on
//! the dock.
//!
//! Finding the program asks the shell: worker threads only.

use super::App;
use crate::settings::dock::Pin;
use std::path::PathBuf;
use windows::core::HSTRING;
use windows::Win32::UI::Shell::{IShellItem, SHCreateItemFromParsingName};

/// The pin for `app`, or None for what the dock could not start (a classic entry that is no
/// program, such as a console snap-in). Blocks while the shell is asked for the program behind
/// an entry.
pub fn pin_of(app: &App) -> Option<Pin> {
    make(app, program_of(app))
}

fn make(app: &App, program: Option<PathBuf>) -> Option<Pin> {
    if is_packaged(&app.id) {
        return Some(Pin::new(app.id.clone(), None));
    }
    match program {
        Some(exe) if !names_itself(app) => Some(Pin::new(exe.to_string_lossy().to_lowercase(), Some(exe))),
        exe if names_itself(app) => Some(Pin::new(app.id.clone(), exe)),
        // A shortcut to something else (a script, a document): pinned as itself.
        _ if app.direct => Some(Pin::new(app.id.to_lowercase(), Some(PathBuf::from(&app.id)))),
        // An id that is no path opens through the Apps folder.
        _ if !app.id.contains('\\') => Some(Pin::new(app.id.clone(), None)),
        _ => None,
    }
}

fn is_packaged(id: &str) -> bool {
    id.contains('!') && !id.contains('\\')
}

/// Whether the entry's id is an AppUserModelID its shortcut gives it (so its windows carry it),
/// rather than a path or one Windows made up for a shortcut that names none.
fn names_itself(app: &App) -> bool {
    !app.direct && !app.id.contains(['\\', '/', ':']) && !app.id.starts_with("Microsoft.AutoGenerated.")
}

/// The program `app` starts, when it is one: the entry itself, the one enumeration found, or the
/// shell's answer for the entry or shortcut.
fn program_of(app: &App) -> Option<PathBuf> {
    let is_exe = |p: &str| p.to_lowercase().ends_with(".exe") && p.contains(":\\");
    if is_exe(&app.id) {
        return Some(PathBuf::from(&app.id));
    }
    if is_exe(&app.target) {
        return Some(PathBuf::from(&app.target));
    }
    if is_packaged(&app.id) {
        return None;
    }
    let item: IShellItem = unsafe { SHCreateItemFromParsingName(&HSTRING::from(app.shell_path()), None) }.ok()?;
    let target = unsafe { super::enumerate::target_of(&item) }?;
    is_exe(&target).then(|| PathBuf::from(target))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pins_match_how_the_dock_groups_windows() {
        // A Store app: its id, started through the Apps folder.
        let calc = App::new("Calculator", "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App");
        assert_eq!(make(&calc, None), Some(Pin::new(calc.id.clone(), None)));
        // An id the shortcut names: kept, with the program for the icon.
        let firefox = App::new("Firefox", "308046B0AF4A39CB");
        let exe = PathBuf::from(r"C:\Program Files\Mozilla Firefox\firefox.exe");
        assert_eq!(make(&firefox, Some(exe.clone())), Some(Pin::new("308046B0AF4A39CB", Some(exe))));
        // A plain program, a made-up id and a shortcut: the program's path.
        let by_path = |app: &App, exe: &str| {
            assert_eq!(make(app, Some(exe.into())), Some(Pin::new(exe.to_lowercase(), Some(exe.into()))));
        };
        by_path(&App::new("7-Zip", r"{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}\7-Zip\7zFM.exe"), r"C:\Program Files\7-Zip\7zFM.exe");
        by_path(&App::new("Local Security Policy", "Microsoft.AutoGenerated.{ABC}"), r"C:\Tools\x.exe");
        by_path(&App { direct: true, ..App::new("Tool", r"C:\sm\Tool.lnk") }, r"C:\Tools\Tool.exe");
        // Nothing found: the entry itself, started through the Apps folder; a shortcut as itself;
        // a classic entry that is no program not at all.
        let odd = App::new("Odd", "Some.Id");
        assert_eq!(make(&odd, None), Some(Pin::new("Some.Id", None)));
        let script = App { direct: true, ..App::new("Script", r"C:\sm\Script.lnk") };
        assert_eq!(make(&script, None), Some(Pin::new(r"c:\sm\script.lnk",Some(r"C:\sm\Script.lnk".into()))));
        assert_eq!(make(&App::new("Snap-in", r"{1AC14E77}\x.msc"), None), None);
    }
}
