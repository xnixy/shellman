//! Working out what a Windows app is called in an icon pack. Pure: no disk, no Windows.
//!
//! An app is known by several names (its program's file name, its package or AUMID, the name on
//! its shortcut) and a pack by one (`visual-studio-code`). `candidates` lists every plausible
//! pack name for an app, best first; the index (see `index.rs`) takes the first one it has.

use std::path::Path;

/// What is known about an app. Any part may be missing.
#[derive(Clone, Copy, Debug, Default)]
pub struct AppRef<'a> {
    /// The app's identity: an AUMID, a package family name, or a program path.
    pub id: &'a str,
    pub exe: Option<&'a Path>,
    /// The name on its shortcut or in the Apps list.
    pub name: Option<&'a str>,
}

/// File extensions that are not part of an app's name.
const APP_EXTENSIONS: [&str; 6] = [".exe", ".lnk", ".url", ".msi", ".appref-ms", ".bat"];

/// Names too generic to say anything: a program called `setup` is not the pack's `setup` icon.
const GENERIC: &[&str] = &[
    "setup", "install", "installer", "uninstall", "uninstaller", "update", "updater", "launcher", "app", "main", "run", "start", "help",
    "client", "bin", "game", "application", "program", "program-files", "windows", "microsoft", "system", "tool", "tools", "settings",
    "desktop", "manager", "service", "documentation", "samples", "sample", "support", "release-notes", "faq", "readme",
];

/// A name that is an identifier rather than a name: a GUID, a long hex string, only digits.
fn is_identifier(name: &str) -> bool {
    if name.contains("autogenerated") {
        return true;
    }
    let last = name.rsplit('.').next().unwrap_or(name).replace('-', "");
    let digits_only = name.chars().all(|c| c.is_ascii_digit() || c == '.' || c == '-');
    let hex = last.len() >= 12 && last.chars().all(|c| c.is_ascii_hexdigit());
    digits_only || hex
}

/// A name in pack form: lower case, spaces and underscores as hyphens, no program extension, no
/// punctuation but `-`, `.` and `+`.
pub fn normalise(text: &str) -> String {
    let file = text.rsplit(['\\', '/']).next().unwrap_or(text).trim();
    let mut lower = file.to_lowercase();
    for ext in APP_EXTENSIONS {
        if let Some(stem) = lower.strip_suffix(ext) {
            lower = stem.to_string();
            break;
        }
    }
    let mut out = String::with_capacity(lower.len());
    for c in lower.chars() {
        match c {
            ' ' | '_' | '-' => out.push('-'),
            '.' | '+' => out.push(c),
            c if c.is_alphanumeric() => out.push(c),
            _ => {}
        }
    }
    collapse(&out)
}

/// One `-` at a time, none at the ends.
fn collapse(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if c == '-' && out.ends_with('-') {
            continue;
        }
        out.push(c);
    }
    out.trim_matches(['-', '.']).to_string()
}

/// Only letters and digits: `Visual Studio Code`, `visual-studio-code` and `visualstudiocode` all
/// squash to the same thing.
pub fn squash(text: &str) -> String {
    text.chars().filter(|c| c.is_alphanumeric()).flat_map(char::to_lowercase).collect()
}

/// Is this hyphen-separated token a version number or an architecture, not part of the name?
fn is_version_token(t: &str) -> bool {
    if matches!(t, "x64" | "x86" | "x32" | "64bit" | "32bit" | "64" | "32" | "win64" | "win32" | "amd64" | "arm64" | "portable" | "stable") {
        return true;
    }
    let t = t.strip_prefix('v').unwrap_or(t);
    !t.is_empty() && t.chars().all(|c| c.is_ascii_digit() || c == '.') && t.chars().any(|c| c.is_ascii_digit())
}

/// `firefox-esr-115.2` is `firefox-esr`; `obs64` is `obs`; `Foo (x64)` is `foo`.
pub fn strip_version(name: &str) -> String {
    let mut tokens: Vec<&str> = name.split('-').collect();
    while tokens.len() > 1 && tokens.last().is_some_and(|t| is_version_token(t)) {
        tokens.pop();
    }
    let joined = tokens.join("-");
    // `obs64`, `idea64`, `devenv32`: the architecture glued to the name.
    for arch in ["64", "32"] {
        if let Some(stem) = joined.strip_suffix(arch) {
            if stem.len() >= 3 && stem.chars().last().is_some_and(char::is_alphabetic) {
                return stem.to_string();
            }
        }
    }
    joined
}

/// Drop parenthesised and bracketed parts: `7-Zip (64-bit)`.
fn strip_brackets(text: &str) -> String {
    let mut out = String::new();
    let mut depth = 0;
    for c in text.chars() {
        match c {
            '(' | '[' => depth += 1,
            ')' | ']' if depth > 0 => depth -= 1,
            c if depth == 0 => out.push(c),
            _ => {}
        }
    }
    out
}

/// Add `name`, its version-stripped form, and nothing twice. Generic and tiny names are left out.
fn push_variants(out: &mut Vec<String>, name: &str) {
    for n in [name.to_string(), strip_version(name)] {
        if n.chars().count() < 2 || GENERIC.contains(&n.as_str()) || is_identifier(&n) || out.contains(&n) {
            continue;
        }
        out.push(n);
    }
}

/// The parts of an AUMID or package family name worth trying: the app part after `!` when it says
/// something, the package's last word, and the whole name.
fn id_names(id: &str) -> Vec<String> {
    if id.contains('\\') || id.contains('/') {
        // A path (a classic app's id in the Apps folder): its file name.
        let file = id.rsplit(['\\', '/']).next().unwrap_or(id);
        return vec![normalise(&strip_brackets(file))];
    }
    let (package, app) = match id.split_once('!') {
        Some((p, a)) => (p, Some(a)),
        None => (id, None),
    };
    // `Microsoft.WindowsTerminal_8wekyb3d8bbwe`: the family name's hash is not part of the name.
    let package = package.split('_').next().unwrap_or(package);
    let mut out = Vec::new();
    if let Some(app) = app {
        let app = normalise(app);
        if !matches!(app.as_str(), "app" | "application" | "") {
            out.push(app);
        }
    }
    let whole = normalise(package);
    let segments: Vec<&str> = whole.split('.').filter(|s| !s.is_empty()).collect();
    if let Some(last) = segments.last() {
        out.push((*last).to_string());
    }
    if segments.len() > 1 {
        // `microsoft.windows.photos`: the last two words together as well, `windows.photos`.
        out.push(whole.clone());
    }
    out
}

/// Every plausible pack name for the app, best first, without duplicates. The program's own file
/// name leads (it is the most exact), then the identity, then the name on the shortcut.
pub fn candidates(app: &AppRef) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    if let Some(exe) = app.exe {
        if let Some(file) = exe.file_name().and_then(|f| f.to_str()) {
            push_variants(&mut out, &normalise(&strip_brackets(file)));
        }
    }
    if !app.id.is_empty() {
        for n in id_names(app.id) {
            push_variants(&mut out, &n);
        }
    }
    if let Some(name) = app.name {
        let n = normalise(&strip_brackets(name));
        push_variants(&mut out, &n);
        // Two words and more, `Visual Studio Code Insiders`: also the first words alone.
        let words: Vec<&str> = n.split('-').collect();
        if words.len() > 2 {
            push_variants(&mut out, &words[..2].join("-"));
        }
        // `Firefox Private Browsing`, `Steam Support Center`: the first word is the app.
        if words.len() > 1 && words[0].chars().count() >= 4 {
            push_variants(&mut out, words[0]);
        }
    }
    out
}

